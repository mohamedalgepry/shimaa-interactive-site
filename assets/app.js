let i = 0;
const answers = [];

function render() {
  const q = questions[i];
  $('#count').textContent = `${String(i + 1).padStart(2, '0')} / ${questions.length}`;
  $('#qnum').textContent = `السؤال ${String(i + 1).padStart(2, '0')}`;
  $('#question').textContent = q[0];
  const percent = Math.round((i / questions.length) * 100);
  $('#progress').style.width = `${percent}%`;
  $('#progressText').textContent = `${percent}%`;
  $('#options').innerHTML = '';
  $('#custom').classList.toggle('hidden', !q[2]);
  $('#customAnswer').value = '';

  q[1].forEach((option, k) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'option';
    button.innerHTML = `<b>${String.fromCharCode(1571 + k)}</b><span>${option}</span>`;
    button.addEventListener('click', () => answer(option));
    $('#options').appendChild(button);
  });

  $('#micro').textContent = q[2]
    ? 'دي أهم واحدة... اكتبيها من قلبك ومن غير تفكير كتير.'
    : 'اختاري اللي شبهنا أكتر.';
}

function answer(value) {
  answers.push({ question: questions[i][0], answer: value });
  next();
}

function next() {
  i += 1;
  if (i < questions.length) {
    render();
  } else {
    finish();
  }
}

$('#start').addEventListener('click', () => {
  if ($('#name').value.trim() !== 'شيماء') {
    $('#hint').textContent = 'استني... إحنا عارفين إن شيماء هي اللي المفروض تدخل.';
    return;
  }
  show('quiz');
  render();
});

$('#name').addEventListener('keydown', (e) => {
  if (e.key === 'Enter') $('#start').click();
});

$('#customNext').addEventListener('click', () => {
  const value = $('#customAnswer').value.trim();
  if (!value) {
    $('#customAnswer').focus();
    return;
  }
  answer(value);
});

function finish() {
  fetch('api/save.php', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ name: 'شيماء', answers })
  }).catch(() => {});
  show('finish');
}

